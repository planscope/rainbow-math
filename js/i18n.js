export function t(lang, key, params = {}) {
  const dict = STR[lang] || STR.en;
  let s = dict[key] ?? STR.en[key];
  if (s == null) return key;
  if (Array.isArray(s)) s = s[(params.pick ?? 0) % s.length];
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

export const pick = (lang, key, rng = Math.random) => {
  const arr = (STR[lang] || STR.en)[key];
  return arr[Math.floor(rng() * arr.length)];
};

